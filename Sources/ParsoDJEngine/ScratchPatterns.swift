/// Mutable control-side draft for a Scratch Bank pattern.
///
/// The editor keeps events ordered by offset and only commits valid changes.
/// It is intentionally a value type so a phone/iPad editor can update a draft
/// off to the side and assign the finished `pattern` to a bank slot atomically.
public struct ScratchPatternEditor: Equatable, Sendable {
    public private(set) var name: String
    public private(set) var technique: ScratchTechnique
    public private(set) var events: [ScratchPatternEvent]

    public init(pattern: ScratchPattern) {
        name = pattern.name
        technique = pattern.technique
        events = pattern.events
    }

    public init(
        name: String,
        technique: ScratchTechnique,
        events: [ScratchPatternEvent] = []
    ) {
        precondition(!name.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                     "Scratch pattern name cannot be empty")
        precondition(zip(events, events.dropFirst()).allSatisfy { $0.0.offset <= $0.1.offset },
                     "Scratch pattern events must be in offset order")
        self.name = name
        self.technique = technique
        self.events = events
    }

    /// The immutable value suitable for `ScratchBank.assign`.
    public var pattern: ScratchPattern {
        ScratchPattern(name: name, technique: technique, events: events)
    }

    @discardableResult
    public mutating func rename(_ name: String) -> Bool {
        guard !name.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return false }
        self.name = name
        return true
    }

    public mutating func setTechnique(_ technique: ScratchTechnique) {
        self.technique = technique
    }

    /// Inserts an event at the requested index when it preserves timeline order.
    @discardableResult
    public mutating func insert(_ event: ScratchPatternEvent, at index: Int) -> Bool {
        guard events.indices.contains(index) || index == events.endIndex else { return false }
        if index > events.startIndex, events[index - 1].offset > event.offset { return false }
        if index < events.endIndex, event.offset > events[index].offset { return false }
        events.insert(event, at: index)
        return true
    }

    @discardableResult
    public mutating func append(_ event: ScratchPatternEvent) -> Bool {
        insert(event, at: events.endIndex)
    }

    /// Replaces an event when the replacement remains ordered with its neighbors.
    @discardableResult
    public mutating func updateEvent(at index: Int, with event: ScratchPatternEvent) -> Bool {
        guard events.indices.contains(index) else { return false }
        if index > events.startIndex, events[index - 1].offset > event.offset { return false }
        if index + 1 < events.endIndex, event.offset > events[index + 1].offset { return false }
        events[index] = event
        return true
    }

    @discardableResult
    public mutating func removeEvent(at index: Int) -> Bool {
        guard events.indices.contains(index) else { return false }
        events.remove(at: index)
        return true
    }

    public mutating func removeAllEvents() {
        events.removeAll(keepingCapacity: true)
    }
}

/// Main-actor recorder that converts timestamped live gestures into a pattern.
///
/// A display-link or gesture coordinator supplies monotonic elapsed time. The
/// recorder stores only control events and never runs on, or synchronizes with,
/// the real-time audio thread. Calling `finish()` returns `nil` for an empty
/// recording; callers can edit the returned pattern before assigning it to a
/// Scratch Bank slot.
@MainActor
public final class ScratchPatternRecorder {
    public let name: String
    public let technique: ScratchTechnique
    public private(set) var isRecording = false
    public private(set) var elapsed: TimeInterval = 0
    public private(set) var events: [ScratchPatternEvent] = []

    /// Best-effort live label for the current take. The original event stream
    /// remains authoritative and can always be corrected in the editor.
    public var recognition: ScratchTechniqueRecognition? {
        ScratchTechniqueRecognizer().recognize(events: events)
    }

    public init(name: String, technique: ScratchTechnique) {
        precondition(!name.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                     "Scratch recording name cannot be empty")
        self.name = name
        self.technique = technique
    }

    public func start() {
        events.removeAll(keepingCapacity: true)
        elapsed = 0
        isRecording = true
    }

    /// Advances the recording clock without adding an event.
    @discardableResult
    public func advance(to elapsed: TimeInterval) -> Bool {
        guard isRecording, elapsed.isFinite, elapsed >= self.elapsed else { return false }
        self.elapsed = elapsed
        return true
    }

    /// Records one jog/fader sample at a monotonic host-clock timestamp.
    @discardableResult
    public func record(
        at elapsed: TimeInterval,
        deltaSamples: Double,
        faderOpen: Bool = true,
        label: String = "",
        pressure: Double = 1
    ) -> Bool {
        guard isRecording, elapsed.isFinite, elapsed >= self.elapsed,
              pressure.isFinite, (0...1).contains(pressure) else { return false }
        let event = ScratchPatternEvent(
            offset: elapsed,
            deltaSamples: deltaSamples,
            faderOpen: faderOpen,
            label: label,
            pressure: pressure
        )
        events.append(event)
        self.elapsed = elapsed
        return true
    }

    @discardableResult
    public func record(
        _ sample: MobilePlatterGestureSample,
        at elapsed: TimeInterval,
        faderOpen: Bool = true,
        label: String = ""
    ) -> Bool {
        record(
            at: elapsed,
            deltaSamples: sample.deltaSamples,
            faderOpen: faderOpen,
            label: label,
            pressure: sample.pressure
        )
    }

    /// Ends the recording and returns an immutable pattern, if it captured an event.
    public func finish() -> ScratchPattern? {
        guard isRecording else { return nil }
        isRecording = false
        guard !events.isEmpty else { return nil }
        return ScratchPattern(name: name, technique: technique, events: events)
    }

    /// Finishes the take using the deterministic control-topology recognizer.
    /// This is a convenience for a UI that wants an initial label; it does not
    /// alter the captured timing, pressure, or fader events.
    public func finishRecognized() -> ScratchPattern? {
        guard isRecording else { return nil }
        isRecording = false
        guard !events.isEmpty else { return nil }
        let detected = recognition?.technique ?? technique
        return ScratchPattern(name: name, technique: detected, events: events)
    }

    public func cancel() {
        isRecording = false
        elapsed = 0
        events.removeAll(keepingCapacity: true)
    }
}

/// Main-actor-owned eight-pad Scratch Bank.
///
/// The bank stores patterns but does not run a timer. A UI/display-link layer
/// obtains a cursor with `cursor(for:)`, advances it using elapsed time, and
/// applies the returned events to a deck and its channel fader. Keeping the
/// clock in the host makes pad triggering deterministic and avoids putting
/// Swift scheduling or allocations anywhere near the audio callback.
@MainActor
public final class ScratchBank {
    public static let slotCount = 8

    public private(set) var slots: [ScratchPattern?]
    private var players: [ObjectIdentifier: ScratchPatternPlayer] = [:]

    public init() {
        slots = Array(repeating: nil, count: Self.slotCount)
    }

    /// Assigns a pattern to a pad. Slots use the same zero-based indexing as
    /// `Deck.padPress(_:)`, so valid values are 0…7.
    @discardableResult
    public func assign(_ pattern: ScratchPattern, to slot: Int) -> Bool {
        guard slots.indices.contains(slot) else { return false }
        slots[slot] = pattern
        return true
    }

    public func pattern(at slot: Int) -> ScratchPattern? {
        guard slots.indices.contains(slot) else { return nil }
        return slots[slot]
    }

    public func editor(for slot: Int) -> ScratchPatternEditor? {
        guard let pattern = pattern(at: slot) else { return nil }
        return ScratchPatternEditor(pattern: pattern)
    }

    @discardableResult
    public func assign(_ editor: ScratchPatternEditor, to slot: Int) -> Bool {
        assign(editor.pattern, to: slot)
    }

    @discardableResult
    public func clear(slot: Int) -> Bool {
        guard slots.indices.contains(slot) else { return false }
        slots[slot] = nil
        return true
    }

    public func cursor(for slot: Int) -> ScratchPatternCursor? {
        guard let pattern = pattern(at: slot) else { return nil }
        return ScratchPatternCursor(pattern: pattern)
    }

    /// Starts a stored pattern on a deck and its corresponding channel.
    ///
    /// The first event is applied immediately. Subsequent events are advanced
    /// by `DJEngine.tickAutomation(elapsed:)` or by `HeadlessDJEngine.render`.
    /// Triggering an occupied deck cancels its previous routine first.
    @discardableResult
    public func trigger(
        _ slot: Int,
        on deck: Deck,
        channel: Channel,
        looping: Bool = false
    ) -> Bool {
        guard let pattern = pattern(at: slot), !pattern.events.isEmpty else { return false }
        stop(on: deck)
        let player = ScratchPatternPlayer(deck: deck, channel: channel)
        players[ObjectIdentifier(deck)] = player
        player.start(pattern: pattern, looping: looping)
        if !player.isActive { players[ObjectIdentifier(deck)] = nil }
        return player.isActive
    }

    /// Stops the active routine on a deck and restores its pre-pattern fader.
    public func stop(on deck: Deck) {
        let id = ObjectIdentifier(deck)
        players.removeValue(forKey: id)?.stop()
    }

    /// Stops every active routine and restores all affected channel faders.
    public func stopAll() {
        let activePlayers = Array(players.values)
        players.removeAll(keepingCapacity: true)
        activePlayers.forEach { $0.stop() }
    }

    public func isPlaying(on deck: Deck) -> Bool {
        players[ObjectIdentifier(deck)]?.isActive == true
    }

    /// Advances all active routines from the host/control clock.
    internal func advance(elapsed: TimeInterval) {
        guard elapsed.isFinite, elapsed >= 0 else { return }
        var finishedIDs: [ObjectIdentifier] = []
        for (id, player) in players {
            player.advance(elapsed: elapsed)
            if !player.isActive { finishedIDs.append(id) }
        }
        for id in finishedIDs { players[id] = nil }
    }
}

/// Control-side Scratch Bank playback for one deck/channel pair.
///
/// This object only posts the same `Deck` jog commands and `Channel` fader
/// controls used by a human gesture. It never renders audio, sleeps, or owns
/// a timer. That keeps pattern playback deterministic in tests and lets a
/// phone/iPad display link provide the clock without affecting the audio
/// callback.
@MainActor
public final class ScratchPatternPlayer {
    public private(set) var isActive = false
    public private(set) var elapsed: TimeInterval = 0
    public private(set) var pattern: ScratchPattern?
    public private(set) var looping = false

    private let deck: Deck
    private let channel: Channel
    private var cursor: ScratchPatternCursor?
    private var originalFader: Double = 1
    private var ownsJogTouch = false

    fileprivate init(deck: Deck, channel: Channel) {
        self.deck = deck
        self.channel = channel
    }

    fileprivate func start(pattern: ScratchPattern, looping: Bool) {
        stop()
        guard !pattern.events.isEmpty else { return }
        self.pattern = pattern
        self.cursor = ScratchPatternCursor(pattern: pattern)
        self.looping = looping
        self.elapsed = 0
        self.originalFader = channel.fader
        deck.jogTouchBegan()
        ownsJogTouch = true
        isActive = true
        advance(elapsed: 0)
    }

    /// Applies every event that became due during `elapsed` seconds.
    fileprivate func advance(elapsed delta: TimeInterval) {
        guard isActive, delta.isFinite, delta >= 0, var cursor, let pattern else { return }
        let duration = max(pattern.duration, 0.001)
        self.elapsed += delta

        while isActive {
            for event in cursor.advance(to: self.elapsed) {
                channel.fader = event.faderOpen ? 1 : 0
                deck.jogMoved(deltaSamples: event.deltaSamples, pressure: event.pressure)
            }
            if !cursor.isFinished { break }
            guard looping else {
                self.cursor = cursor
                finish()
                return
            }
            self.elapsed -= duration
            cursor.reset()
        }
        self.cursor = cursor
    }

    fileprivate func stop() {
        guard isActive else { return }
        finish()
    }

    private func finish() {
        if ownsJogTouch {
            deck.jogTouchEnded()
            ownsJogTouch = false
        }
        channel.fader = originalFader
        isActive = false
        looping = false
    }
}

/// Deterministic host-side cursor for driving a pattern timeline.
public struct ScratchPatternCursor: Sendable {
    public let pattern: ScratchPattern
    public private(set) var nextEventIndex: Int = 0

    public init(pattern: ScratchPattern) {
        self.pattern = pattern
    }

    public var isFinished: Bool { nextEventIndex >= pattern.events.count }

    /// Returns each event whose offset is at or before `elapsed` exactly once.
    /// Calling with an earlier time leaves the cursor unchanged.
    public mutating func advance(to elapsed: TimeInterval) -> [ScratchPatternEvent] {
        guard elapsed.isFinite, elapsed >= 0 else { return [] }
        var end = nextEventIndex
        while end < pattern.events.count, pattern.events[end].offset <= elapsed {
            end += 1
        }
        guard end > nextEventIndex else { return [] }
        let result = Array(pattern.events[nextEventIndex..<end])
        nextEventIndex = end
        return result
    }

    public mutating func reset() {
        nextEventIndex = 0
    }
}
