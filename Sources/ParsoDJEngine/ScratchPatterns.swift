import Foundation

/// The named turntablism technique represented by a scratch pattern.
public enum ScratchTechnique: String, CaseIterable, Hashable, Sendable {
    case baby
    case scribble
    case drag
    case forward
    case backward
    case chirp
    case flare
    case orbit
    case transform
    case crab
    case tear
    case twiddle
    case boomerang
}

/// One normalized touch sample from a circular phone/iPad platter.
public struct MobilePlatterGestureSample: Equatable, Sendable {
    /// Source-frame movement generated by the platter mapper.
    public let deltaSamples: Double
    /// Normalized contact pressure, where zero means no record contact.
    public let pressure: Double
    /// Signed source-frame velocity at this sample.
    public let velocitySamplesPerSecond: Double

    public init(
        deltaSamples: Double,
        pressure: Double,
        velocitySamplesPerSecond: Double
    ) {
        precondition(deltaSamples.isFinite, "Platter delta must be finite")
        precondition(pressure.isFinite && (0...1).contains(pressure),
                     "Platter pressure must be within 0...1")
        precondition(velocitySamplesPerSecond.isFinite, "Platter velocity must be finite")
        self.deltaSamples = deltaSamples
        self.pressure = pressure
        self.velocitySamplesPerSecond = velocitySamplesPerSecond
    }
}

/// Converts circular normalized touch coordinates into turntable movement.
///
/// The mapper uses the shortest path across the 0/1 platter seam and derives
/// velocity from host timestamps. It has no timer and performs no audio work;
/// a UI display link can feed each returned sample to `Deck.jogMoved(_:)`.
public struct MobilePlatterGestureMapper: Sendable {
    public let samplesPerRevolution: Double
    public let sensitivity: Double

    private var lastPosition: Double?
    private var lastTimestamp: TimeInterval?

    public var isTracking: Bool { lastPosition != nil }

    public init(samplesPerRevolution: Double, sensitivity: Double = 1) {
        precondition(samplesPerRevolution.isFinite && samplesPerRevolution > 0,
                     "Platter samples-per-revolution must be positive")
        precondition(sensitivity.isFinite && sensitivity > 0,
                     "Platter sensitivity must be positive")
        self.samplesPerRevolution = samplesPerRevolution
        self.sensitivity = sensitivity
    }

    /// Starts a touch track. The first sample has no movement.
    @discardableResult
    public mutating func begin(at position: Double, timestamp: TimeInterval, pressure: Double = 1)
        -> MobilePlatterGestureSample?
    {
        guard let position = normalizedPosition(position),
              normalizedPressure(pressure) != nil,
              timestamp.isFinite else { return nil }
        lastPosition = position
        lastTimestamp = timestamp
        return nil
    }

    /// Returns movement from the previous touch sample, or `nil` for invalid or
    /// non-monotonic host timestamps.
    public mutating func update(
        to position: Double,
        timestamp: TimeInterval,
        pressure: Double = 1
    ) -> MobilePlatterGestureSample? {
        guard let position = normalizedPosition(position),
              let pressure = normalizedPressure(pressure),
              timestamp.isFinite,
              let previousPosition = lastPosition,
              let previousTimestamp = lastTimestamp,
              timestamp >= previousTimestamp else { return nil }

        var rotation = position - previousPosition
        if rotation > 0.5 { rotation -= 1 }
        if rotation < -0.5 { rotation += 1 }
        let deltaSamples = rotation * samplesPerRevolution * sensitivity
        let duration = timestamp - previousTimestamp
        let velocity = duration > 0 ? deltaSamples / duration : 0
        lastPosition = position
        lastTimestamp = timestamp
        return MobilePlatterGestureSample(
            deltaSamples: deltaSamples,
            pressure: pressure,
            velocitySamplesPerSecond: velocity
        )
    }

    public mutating func end() {
        lastPosition = nil
        lastTimestamp = nil
    }

    private func normalizedPosition(_ position: Double) -> Double? {
        guard position.isFinite, (0...1).contains(position) else { return nil }
        return position == 1 ? 0 : position
    }

    private func normalizedPressure(_ pressure: Double) -> Double? {
        guard pressure.isFinite else { return nil }
        return max(0, min(1, pressure))
    }
}

/// Main-actor bridge between a mobile platter gesture and one deck.
///
/// The session owns begin/update/end ordering. Updates received before begin
/// or after end are ignored, and ending the session always releases the deck's
/// vinyl touch. This keeps UIKit/SwiftUI gesture cancellation from leaving a
/// deck stuck in scratch mode or applying a stale sample to a later touch.
@MainActor
public final class MobilePlatterGestureSession {
    public private(set) var isActive = false
    public private(set) var lastSample: MobilePlatterGestureSample?

    private let deck: Deck
    private var mapper: MobilePlatterGestureMapper

    public init(deck: Deck, samplesPerRevolution: Double, sensitivity: Double = 1) {
        self.deck = deck
        mapper = MobilePlatterGestureMapper(
            samplesPerRevolution: samplesPerRevolution,
            sensitivity: sensitivity
        )
    }

    @discardableResult
    public func begin(
        at position: Double,
        timestamp: TimeInterval,
        pressure: Double = 1
    ) -> Bool {
        guard !isActive else { return false }
        mapper.begin(at: position, timestamp: timestamp, pressure: pressure)
        guard mapper.isTracking else { return false }
        isActive = true
        lastSample = nil
        deck.jogTouchBegan(pressure: normalizedPressure(pressure))
        return true
    }

    @discardableResult
    public func update(
        to position: Double,
        timestamp: TimeInterval,
        pressure: Double = 1
    ) -> MobilePlatterGestureSample? {
        guard isActive, let sample = mapper.update(
            to: position, timestamp: timestamp, pressure: pressure
        ) else { return nil }
        lastSample = sample
        deck.jogMoved(sample)
        return sample
    }

    public func end() {
        guard isActive else { return }
        mapper.end()
        deck.jogTouchEnded()
        isActive = false
        lastSample = nil
    }

    public func cancel() {
        end()
    }

    private func normalizedPressure(_ pressure: Double) -> Double {
        guard pressure.isFinite else { return 0 }
        return max(0, min(1, pressure))
    }
}

/// One timestamped control event in a reusable scratch routine.
///
/// `deltaSamples` is a source-deck movement, suitable for passing to
/// `Deck.jogMoved(deltaSamples:)`. `faderOpen` is the desired channel-fader
/// state at that event. A zero-delta event is intentionally allowed so a
/// routine can express a fader click without moving the record. The host owns
/// the clock and applies events on the main actor; no event scheduling or
/// allocation is performed by the real-time renderer.
public struct ScratchPatternEvent: Equatable, Sendable {
    /// Elapsed time from the start of the routine, in seconds.
    public let offset: TimeInterval
    /// Signed source-deck movement in sample frames.
    public let deltaSamples: Double
    /// Whether the channel fader should be open at this event.
    public let faderOpen: Bool
    /// Normalized contact pressure captured from a mobile platter.
    public let pressure: Double
    /// Optional UI-facing description for a pad editor or guided review.
    public let label: String

    public init(
        offset: TimeInterval,
        deltaSamples: Double,
        faderOpen: Bool = true,
        label: String = "",
        pressure: Double = 1
    ) {
        precondition(offset.isFinite && offset >= 0, "Scratch event offset must be finite and non-negative")
        precondition(deltaSamples.isFinite, "Scratch event delta must be finite")
        precondition(pressure.isFinite && (0...1).contains(pressure),
                     "Scratch event pressure must be within 0...1")
        self.offset = offset
        self.deltaSamples = deltaSamples
        self.faderOpen = faderOpen
        self.label = label
        self.pressure = pressure
    }
}

